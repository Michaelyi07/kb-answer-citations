"""JSON Schema (Draft 2020-12) for kb_answer model output.

Output contract (S3-KB-020):
    {points: [{text, citations: [n]}], refused: boolean}
- every point must cite at least one evidence block (minItems=1 on citations)
- refused=true means "insufficient evidence" refusal; points must then be empty
- citation numbers must be positive integers pointing into the evidence blocks
"""

from __future__ import annotations

import json
from typing import Any

from jsonschema import Draft202012Validator

ANSWER_SCHEMA: dict[str, Any] = {
    "$schema": "https://json-schema.org/draft/2020-12/schema",
    "$id": "https://kb.internal.local/schemas/kb_answer.v1.json",
    "title": "KBAnswer",
    "description": (
        "Answer generated by prompts/kb_answer/v1. Every point cites at least one "
        "evidence block; refused=true marks an insufficient-evidence refusal."
    ),
    "type": "object",
    "additionalProperties": False,
    "required": ["points", "refused"],
    "properties": {
        "points": {
            "type": "array",
            "items": {
                "type": "object",
                "additionalProperties": False,
                "required": ["text", "citations"],
                "properties": {
                    "text": {"type": "string", "minLength": 1},
                    "citations": {
                        "type": "array",
                        "minItems": 1,
                        "uniqueItems": True,
                        "items": {"type": "integer", "minimum": 1},
                    },
                },
            },
        },
        "refused": {"type": "boolean"},
    },
    "allOf": [
        {
            "if": {"properties": {"refused": {"const": True}}, "required": ["refused"]},
            "then": {"properties": {"points": {"maxItems": 0}}},
        }
    ],
}


def validate_answer(data: Any) -> None:
    """Validate an answer dict against ANSWER_SCHEMA.

    Raises jsonschema.ValidationError on the first violation; returns None on success.
    """
    validator = Draft202012Validator(ANSWER_SCHEMA)
    errors = sorted(validator.iter_errors(data), key=lambda e: list(e.absolute_path))
    if errors:
        first = errors[0]
        path = "/".join(str(p) for p in first.absolute_path) or "<root>"
        raise first.__class__(f"{path}: {first.message}")
    return None


def is_valid_answer(data: Any) -> bool:
    """True if data validates against ANSWER_SCHEMA."""
    return Draft202012Validator(ANSWER_SCHEMA).is_valid(data)


def schema_json() -> str:
    """Pretty-printed schema document (for docs / gateway registration)."""
    return json.dumps(ANSWER_SCHEMA, ensure_ascii=False, indent=2)
